-- PSM Internship Certificate Verification Platform
-- MySQL 8+ schema with relationships
CREATE DATABASE IF NOT EXISTS psm_internship
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;
USE psm_internship;
CREATE TABLE IF NOT EXISTS admins (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(40) NOT NULL DEFAULT 'admin',
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS mentors (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  domain VARCHAR(120) NULL,
  phone VARCHAR(40) NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS company_settings (
  id INT AUTO_INCREMENT PRIMARY KEY,
  company_name VARCHAR(180) NOT NULL,
  tagline VARCHAR(255) NULL,
  official_email VARCHAR(190) NOT NULL,
  phone VARCHAR(40) NULL,
  website VARCHAR(255) NULL,
  address TEXT NULL,
  about TEXT NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS interns (
  id INT AUTO_INCREMENT PRIMARY KEY,
  intern_id VARCHAR(40) NOT NULL UNIQUE,
  full_name VARCHAR(160) NOT NULL,
  email VARCHAR(190) NULL,
  domain VARCHAR(120) NOT NULL,
  photo_path VARCHAR(255) NULL,
  mentor_id INT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_interns_mentor FOREIGN KEY (mentor_id) REFERENCES mentors(id)
    ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS internships (
  id INT AUTO_INCREMENT PRIMARY KEY,
  intern_pk INT NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  duration_label VARCHAR(120) NOT NULL,
  status ENUM('Completed', 'Ongoing', 'Incomplete') NOT NULL DEFAULT 'Ongoing',
  organisation VARCHAR(180) NOT NULL DEFAULT 'Problem Solving Mind',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_internships_intern FOREIGN KEY (intern_pk) REFERENCES interns(id)
    ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS projects (
  id INT AUTO_INCREMENT PRIMARY KEY,
  intern_pk INT NOT NULL,
  title VARCHAR(200) NOT NULL,
  description TEXT NULL,
  technologies VARCHAR(255) NULL,
  github_url VARCHAR(500) NULL,
  live_url VARCHAR(500) NULL,
  status ENUM('Completed', 'In Progress', 'Incomplete') NOT NULL DEFAULT 'In Progress',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_projects_intern FOREIGN KEY (intern_pk) REFERENCES interns(id)
    ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS mentor_evaluations (
  id INT AUTO_INCREMENT PRIMARY KEY,
  intern_pk INT NOT NULL,
  mentor_id INT NULL,
  technical_skills INT NOT NULL DEFAULT 0,
  problem_solving INT NOT NULL DEFAULT 0,
  code_quality INT NOT NULL DEFAULT 0,
  communication INT NOT NULL DEFAULT 0,
  teamwork INT NOT NULL DEFAULT 0,
  total_marks INT NOT NULL DEFAULT 0,
  percentage DECIMAL(5,2) NOT NULL DEFAULT 0,
  grade VARCHAR(10) NULL,
  feedback TEXT NULL,
  is_published TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_eval_intern FOREIGN KEY (intern_pk) REFERENCES interns(id)
    ON DELETE CASCADE,
  CONSTRAINT fk_eval_mentor FOREIGN KEY (mentor_id) REFERENCES mentors(id)
    ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS certificates (
  id INT AUTO_INCREMENT PRIMARY KEY,
   intern_pk INT NOT NULL,
  certificate_id VARCHAR(60) NOT NULL UNIQUE,
  qr_payload VARCHAR(500) NOT NULL,
  qr_image_path VARCHAR(255) NULL,
  pdf_path VARCHAR(255) NULL,
  status ENUM('Valid', 'Pending', 'Revoked', 'Expired') NOT NULL DEFAULT 'Pending',
  issued_at DATETIME NULL,
  expires_at DATETIME NULL,
  revocation_reason TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_cert_intern FOREIGN KEY (intern_pk) REFERENCES interns(id)
    ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS audit_logs (
  id INT AUTO_INCREMENT PRIMARY KEY,
  actor_email VARCHAR(190) NULL,
  action VARCHAR(120) NOT NULL,
  entity_type VARCHAR(80) NULL,
  entity_id VARCHAR(80) NULL,
  details TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);